"""Persistence boundary, shared by all application services."""

from contextlib import AbstractContextManager
from typing import Protocol, runtime_checkable

from .models import (
    Artifact,
    ArtifactReference,
    ContextItem,
    ContextPackage,
    Project,
    ProjectMemory,
    ProjectState,
)


@runtime_checkable
class StorageProvider(Protocol):
    def create_project(self, project: Project) -> None: ...
    def save_project(self, project: Project) -> None: ...
    def load_project(self, project_id: str) -> Project: ...
    def list_projects(self) -> list[Project]: ...
    def save_state(self, project_id: str, state: ProjectState) -> None: ...
    def load_state(self, project_id: str) -> ProjectState: ...
    def save_memory(self, project_id: str, memory: ProjectMemory) -> None: ...
    def load_memory(self, project_id: str) -> ProjectMemory: ...
    def save_artifact(self, project_id: str, artifact: Artifact) -> None: ...
    def load_artifact(self, project_id: str, artifact_id: str, version: str | None = None) -> Artifact: ...
    def list_artifacts(self, project_id: str) -> list[ArtifactReference]: ...
    def save_upload(self, project_id: str, file: bytes, metadata: dict) -> str: ...
    def load_upload(self, project_id: str, file_id: str) -> bytes: ...
    def save_context(self, project_id: str, context: ContextPackage) -> None: ...
    def load_context(self, project_id: str, context_type: str) -> list[ContextItem]: ...
    def list_project_assets(self, project_id: str) -> list[dict]: ...
    def load_session(self, project_id: str) -> dict: ...
    def save_session(self, project_id: str, session: dict) -> None: ...
    def append_event(self, project_id: str, event: dict) -> None: ...
    def list_events(self, project_id: str) -> list[dict]: ...
    def transaction(self, project_id: str) -> AbstractContextManager: ...


class StorageConflict(ValueError):
    pass
